// Markdown export of the plan, in the chosen language.
import type { Lang } from "./types";
import type { Plan } from "./engine/plan";
import type { JobMatch } from "./engine/jobs";
import { skillLabel } from "./data";

export function planToMarkdown(plan: Plan, matches: JobMatch[], lang: Lang, claudeText = ""): string {
  const x = (v: { en: string; pt: string } | null | undefined) => (v ? v[lang] || v.en : "");
  const pt = lang === "pt";
  const out: string[] = [];
  out.push(`# ${pt ? "Meu plano" : "My plan"}: ${x(plan.track.name)}`, "");
  out.push(`_${pt ? "Gerado pelo Visa Job Atlas em" : "Generated by Visa Job Atlas on"} ${new Date().toISOString().slice(0, 10)}. ${pt ? "Não é aconselhamento jurídico." : "Not legal advice."}_`, "");
  out.push(`## ${pt ? "Melhores países" : "Best countries"}`, "");
  for (const f of plan.top) {
    out.push(`### ${x(f.country.name)} (${f.score})`);
    for (const r of f.reasons.slice(0, 5)) out.push(`- ${r.delta > 0 ? "+" : ""}${r.delta}: ${x(r.text)}`);
    for (const r of f.country.routes.slice(0, 3)) {
      const floor = r.salaryMin ? ` (${r.salaryMin.amount.toLocaleString()} ${r.salaryMin.currency}/${r.salaryMin.period})` : "";
      out.push(`- **${x(r.name)}**${floor}: ${x(r.summary)} ${r.source}`);
    }
    out.push("");
  }
  if (plan.gaps.length) {
    out.push(`## ${pt ? "Lacunas de habilidades" : "Skill gaps"}`, "");
    out.push(plan.gaps.map((g) => `${skillLabel(g.id)} (${g.count})`).join(", "), "");
  }
  for (const ph of plan.phases) {
    out.push(`## ${x(ph.title)}`, "");
    for (const it of ph.items) out.push(`- [ ] ${x(it.text)}${it.detail ? ` — ${x(it.detail)}` : ""}${it.url ? ` (${it.url})` : ""}`);
    out.push("");
  }
  out.push(`## ${pt ? "Toda semana" : "Every week"}`, "", ...plan.weekly.map((w) => `- ${x(w)}`), "");
  if (matches.length) {
    out.push(`## ${pt ? "Vagas para começar" : "Jobs to start with"}`, "");
    for (const m of matches.slice(0, 20)) out.push(`- [${m.job.title} — ${m.job.company}, ${m.job.location}](${m.job.url})`);
    out.push("");
  }
  if (claudeText) out.push(`## ${pt ? "Plano escrito pelo Claude" : "Plan written by Claude"}`, "", claudeText, "");
  return out.join("\n");
}

export function download(name: string, text: string, type = "text/markdown") {
  const url = URL.createObjectURL(new Blob([text], { type: type + ";charset=utf-8" }));
  const a = document.createElement("a");
  a.href = url;
  a.download = name;
  a.click();
  setTimeout(() => URL.revokeObjectURL(url), 1000);
}
