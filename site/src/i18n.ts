export type StringKey = keyof typeof STRINGS;

export const LangContext = createContext<Lang>("en");

export function useT() {
  const lang = useContext(LangContext);
  const t = (k: StringKey) => STRINGS[k][lang];
  const tx = (v: L10n | null | undefined) => (v ? v[lang] || v.en : "");
  return { t, tx, lang };
}

const regionNames: Partial<Record<Lang, Intl.DisplayNames>> = {};
export function countryName(code: string, lang: Lang): string {
  try {
    regionNames[lang] ??= new Intl.DisplayNames([lang === "pt" ? "pt-BR" : "en"], { type: "region" });
    return regionNames[lang]!.of(code) ?? code;
  } catch {
    return code;
  }
}
const languageNames: Partial<Record<Lang, Intl.DisplayNames>> = {};
export function languageName(code: string, lang: Lang): string {
  try {
    languageNames[lang] ??= new Intl.DisplayNames([lang === "pt" ? "pt-BR" : "en"], { type: "language" });
    return languageNames[lang]!.of(code) ?? code;
  } catch {
    return code;
  }
}
